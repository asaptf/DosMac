import Foundation

/// Original redistributable PC diagnostic. It is not a DOS or Windows image.
public enum DiagnosticBootDisk {
    public static func make() -> Data {
        var disk = Data(repeating: 0, count: 1440 * 1024)
        // BIOS text, then a mode-13h color pattern; a key returns to text.
        var code: [UInt8] = [0xfa,0x31,0xc0,0x8e,0xd8,0x8e,0xd0,0xbc,0,0x7c,0xfb,
            0xb8,3,0,0xcd,0x10,0xbe,0x80,0x7c,0xac,0x84,0xc0,0x74,0x09,0xb4,0x0e,0xbb,7,0,0xcd,0x10,0xeb,0xf2,
            0x31,0xc0,0xcd,0x16,0xb8,0x13,0,0xcd,0x10,0xb8,0,0xa0,0x8e,0xc0,0x31,0xff,
            0xb9,0xc8,0,0x51,0xb0,1,0xbb,0x10,0,0xb9,0x14,0,0xf3,0xaa,0xfe,0xc0,0x4b,0x75,0xf6,0x59,0xe2,0xed,0x31,0xc0,0xcd,0x16,0xe9]
        let displacement = UInt16(truncatingIfNeeded: 11 - (code.count + 2))
        code += [UInt8(displacement & 255), UInt8(displacement >> 8)]
        disk.replaceSubrange(0..<code.count, with: code)
        let text = Data("DosMac PC hardware check\r\n\r\nOriginal BIOS diagnostic - no DOS or Windows required.\r\n\r\nPress Enter to show a color pattern.\r\nPress Enter again to return here.\r\n\0".utf8)
        disk.replaceSubrange(128..<(128+text.count), with: text)
        disk[510] = 0x55; disk[511] = 0xaa
        return disk
    }
}

import Foundation

public enum DOSBoxConfiguration {
    public static func render(program: InstalledProgram, driveC: URL, exchange: URL) throws -> String {
        try program.manifest.validate()
        for url in [driveC, exchange] {
            let forbidden = CharacterSet.controlCharacters.union(CharacterSet(charactersIn: "\"%"))
            guard url.path.unicodeScalars.allSatisfy({ !forbidden.contains($0) }) else { throw DosMacError.invalidPackage("unsafe host path") }
        }
        let entry = program.manifest.executable.replacingOccurrences(of: "\\", with: "/")
        let components = entry.split(separator: "/")
        let directory = components.dropLast().joined(separator: "\\")
        let changeDirectory = directory.isEmpty ? "" : "cd \\\(directory)\n"
        let startCommand = program.manifest.effectiveStartupMode == .dosPrompt ? "cd \\" : changeDirectory + String(components.last!)
        let windowsDirectory = directory.isEmpty ? "C:\\" : "C:\\\(directory)"
        let windowsEnvironment = program.manifest.hasWindowsEntryPoint ? "set PATH=%PATH%;\(windowsDirectory)\nif not exist C:\\TEMP md C:\\TEMP\nset TEMP=C:\\TEMP\nset TMP=C:\\TEMP\n" : ""
        return """
        # Generated by DosMac. CPU interpretation only; no JIT.
        [sdl]
        fullscreen=false
        # Windows' standard mouse driver needs relative input while captured.
        autolock=true
        autolock_feedback=none
        [dosbox]
        machine=svga_s3
        memsize=\(program.manifest.profile.memoryMB)
        [cpu]
        core=normal
        cputype=\(program.manifest.profile.cpu)
        cycles=auto
        [mixer]
        rate=44100
        [sblaster]
        sbtype=sb16
        [ipx]
        ipx=false
        [autoexec]
        @echo off
        mount c "\(driveC.path)"
        mount d "\(exchange.path)"
        c:
        \(windowsEnvironment)\(startCommand)

        """
    }
}
